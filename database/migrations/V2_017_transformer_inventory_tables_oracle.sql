DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tables
     WHERE table_name = 'TRANSFORMATION_MAPPING';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'~
            CREATE TABLE transformation_mapping (
                transformation_mapping_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                transformation_import_id NUMBER NOT NULL,
                statement_number NUMBER NOT NULL,
                execution_order NUMBER NOT NULL,
                target_type VARCHAR2(20 CHAR) NOT NULL,
                operation_type VARCHAR2(20 CHAR) NOT NULL,
                target_schema_name VARCHAR2(128 CHAR) NOT NULL,
                target_table_name VARCHAR2(128 CHAR) NOT NULL,
                target_column_name VARCHAR2(128 CHAR),
                catalog_table_id NUMBER,
                catalog_column_id NUMBER,
                source_expression CLOB,
                filter_expression CLOB,
                detected_algorithm_code VARCHAR2(100 CHAR),
                algorithm_version_id NUMBER,
                parameters_json VARCHAR2(4000 CHAR) DEFAULT '{}' NOT NULL,
                match_status VARCHAR2(30 CHAR) NOT NULL,
                diagnostic_message VARCHAR2(4000 CHAR),
                created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT transformation_mapping_pk PRIMARY KEY (transformation_mapping_id),
                CONSTRAINT transformation_mapping_imp_fk FOREIGN KEY (transformation_import_id)
                    REFERENCES transformation_import (transformation_import_id) ON DELETE CASCADE,
                CONSTRAINT transformation_mapping_tbl_fk FOREIGN KEY (catalog_table_id)
                    REFERENCES catalog_table (catalog_table_id),
                CONSTRAINT transformation_mapping_col_fk FOREIGN KEY (catalog_column_id)
                    REFERENCES catalog_column (catalog_column_id),
                CONSTRAINT transformation_mapping_alg_fk FOREIGN KEY (algorithm_version_id)
                    REFERENCES algorithm_version (algorithm_version_id),
                CONSTRAINT transformation_mapping_type_ck CHECK (target_type IN ('COLUMN','TABLE')),
                CONSTRAINT transformation_mapping_op_ck CHECK (
                    operation_type IN ('UPDATE','DELETE','TRUNCATE')),
                CONSTRAINT transformation_mapping_match_ck CHECK (
                    match_status IN ('MATCHED','UNRESOLVED','REVIEW_REQUIRED','ACCEPTED')),
                CONSTRAINT transformation_mapping_target_ck CHECK (
                    (target_type = 'COLUMN' AND target_column_name IS NOT NULL)
                    OR (target_type = 'TABLE' AND target_column_name IS NULL))
            )
        ~';
        EXECUTE IMMEDIATE
            'CREATE INDEX transformation_mapping_imp_ix '
            || 'ON transformation_mapping(transformation_import_id, execution_order)';
        DBMS_OUTPUT.PUT_LINE('[OK] TRANSFORMATION_MAPPING created');
    ELSE
        DBMS_OUTPUT.PUT_LINE('[SKIP] TRANSFORMATION_MAPPING already exists');
    END IF;
END;
