-- Adds table-level masking rules and enables the built-in structural algorithms.
-- Safe to run repeatedly on repositories created by the V2 baseline.
DECLARE
    table_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO table_count
      FROM user_tables
     WHERE table_name = 'TABLE_MASKING_RULE';

    IF table_count = 0 THEN
        EXECUTE IMMEDIATE q'~
            CREATE TABLE table_masking_rule (
                table_rule_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                ruleset_version_id NUMBER NOT NULL,
                catalog_table_id NUMBER NOT NULL,
                algorithm_version_id NUMBER NOT NULL,
                execution_order NUMBER DEFAULT 100 NOT NULL,
                filter_expression CLOB,
                enabled CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
                created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT table_masking_rule_pk PRIMARY KEY (table_rule_id),
                CONSTRAINT table_masking_rule_uk UNIQUE (ruleset_version_id, catalog_table_id),
                CONSTRAINT table_masking_rule_order_ck CHECK (execution_order >= 0),
                CONSTRAINT table_masking_rule_enabled_ck CHECK (enabled IN ('Y','N')),
                CONSTRAINT tmr_ruleset_version_fk FOREIGN KEY (ruleset_version_id)
                    REFERENCES ruleset_version (ruleset_version_id) ON DELETE CASCADE,
                CONSTRAINT tmr_catalog_table_fk FOREIGN KEY (catalog_table_id)
                    REFERENCES catalog_table (catalog_table_id),
                CONSTRAINT tmr_algorithm_version_fk FOREIGN KEY (algorithm_version_id)
                    REFERENCES algorithm_version (algorithm_version_id)
            )
        ~';
        EXECUTE IMMEDIATE
            'CREATE INDEX table_masking_rule_table_ix ON table_masking_rule(catalog_table_id)';
        EXECUTE IMMEDIATE
            'CREATE INDEX table_masking_rule_algorithm_ix ON table_masking_rule(algorithm_version_id)';
    END IF;
END;
/

UPDATE algorithm_version
   SET status = 'PUBLISHED',
       published_at = NVL(published_at, SYSTIMESTAMP)
 WHERE status = 'DRAFT'
   AND EXISTS (
       SELECT 1 FROM algorithm a
        WHERE a.algorithm_id = algorithm_version.algorithm_id
          AND a.code IN ('DELETE_TABLE_ROWS', 'TRUNCATE_TABLE'));

UPDATE algorithm_implementation
   SET status = 'PUBLISHED',
       published_at = NVL(published_at, SYSTIMESTAMP)
 WHERE status = 'DRAFT'
   AND EXISTS (
       SELECT 1
         FROM algorithm_version av
         JOIN algorithm a ON a.algorithm_id = av.algorithm_id
        WHERE av.algorithm_version_id = algorithm_implementation.algorithm_version_id
          AND a.code IN ('DELETE_TABLE_ROWS', 'TRUNCATE_TABLE'));

COMMIT;
