CREATE TABLE algorithm (
  algorithm_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  code text NOT NULL,
  name text NOT NULL,
  category text NOT NULL,
  description text,
  deterministic text DEFAULT 'N' NOT NULL,
  reversible text DEFAULT 'N' NOT NULL,
  preserve_null text DEFAULT 'Y' NOT NULL,
  preserve_format text DEFAULT 'N' NOT NULL,
  preserve_length text DEFAULT 'N' NOT NULL,
  preserve_uniqueness text DEFAULT 'N' NOT NULL,
  status text DEFAULT 'ACTIVE' NOT NULL,
  created_at timestamptz DEFAULT statement_timestamp() NOT NULL,
  CONSTRAINT algorithm_category_ck CHECK (category IN (
            'MASKING','SUBSTITUTION','RANDOMIZATION','GENERALIZATION','SUPPRESSION',
            'HASHING','TOKENIZATION','SHUFFLING','PERTURBATION','SYNTHETIC','STRUCTURAL'
        )),
  CONSTRAINT algorithm_code_uk UNIQUE (code),
  CONSTRAINT algorithm_deterministic_ck CHECK (deterministic IN ('Y','N')),
  CONSTRAINT algorithm_format_ck CHECK (preserve_format IN ('Y','N')),
  CONSTRAINT algorithm_length_ck CHECK (preserve_length IN ('Y','N')),
  CONSTRAINT algorithm_null_ck CHECK (preserve_null IN ('Y','N')),
  CONSTRAINT algorithm_pk PRIMARY KEY (algorithm_id),
  CONSTRAINT algorithm_reversible_ck CHECK (reversible IN ('Y','N')),
  CONSTRAINT algorithm_status_ck CHECK (status IN ('ACTIVE','DEPRECATED','RETIRED')),
  CONSTRAINT algorithm_unique_ck CHECK (preserve_uniqueness IN ('Y','N'))
);

