-- Privonym application identities and authorization are independent from Oracle users.
SET DEFINE OFF

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name='PRIVONYM_USER';
  IF v_count=0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE privonym_user(
      user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username VARCHAR2(100) NOT NULL,
      display_name VARCHAR2(200) NOT NULL,
      password_hash VARCHAR2(128) NOT NULL,
      password_salt VARCHAR2(128) NOT NULL,
      password_iterations NUMBER(9) NOT NULL,
      administrator CHAR(1) DEFAULT 'N' NOT NULL,
      status VARCHAR2(20) DEFAULT 'ENABLED' NOT NULL,
      failed_login_count NUMBER(5) DEFAULT 0 NOT NULL,
      locked_until TIMESTAMP WITH TIME ZONE,
      last_login_at TIMESTAMP WITH TIME ZONE,
      created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      created_by VARCHAR2(100) NOT NULL,
      updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT privonym_user_username_uk UNIQUE(username),
      CONSTRAINT privonym_user_admin_ck CHECK(administrator IN('Y','N')),
      CONSTRAINT privonym_user_status_ck CHECK(status IN('ENABLED','DISABLED')),
      CONSTRAINT privonym_user_iterations_ck CHECK(password_iterations BETWEEN 100000 AND 2000000)
    )~';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name='PRIVONYM_PRIVILEGE';
  IF v_count=0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE privonym_privilege(
      privilege_code VARCHAR2(50) PRIMARY KEY,
      description VARCHAR2(500) NOT NULL
    )~';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name='PRIVONYM_USER_PRIVILEGE';
  IF v_count=0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE privonym_user_privilege(
      user_id NUMBER NOT NULL REFERENCES privonym_user(user_id) ON DELETE CASCADE,
      privilege_code VARCHAR2(50) NOT NULL REFERENCES privonym_privilege(privilege_code),
      granted_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      granted_by VARCHAR2(100) NOT NULL,
      CONSTRAINT privonym_user_privilege_pk PRIMARY KEY(user_id,privilege_code)
    )~';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name='PRIVONYM_SECURITY_EVENT';
  IF v_count=0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE privonym_security_event(
      security_event_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      event_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      username VARCHAR2(100) NOT NULL,
      action_code VARCHAR2(80) NOT NULL,
      object_type VARCHAR2(50),
      object_reference VARCHAR2(300),
      outcome VARCHAR2(30) NOT NULL
    )~';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tab_columns
   WHERE table_name='RULESET' AND column_name='OWNER_USER_ID';
  IF v_count=0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ruleset ADD(owner_user_id NUMBER)';
    EXECUTE IMMEDIATE 'ALTER TABLE ruleset ADD CONSTRAINT ruleset_owner_user_fk FOREIGN KEY(owner_user_id) REFERENCES privonym_user(user_id)';
  END IF;
END;
/

MERGE INTO privonym_privilege p
USING (
  SELECT 'USER_MANAGE' code,'Create, enable and disable Privonym users' description FROM dual UNION ALL
  SELECT 'ENVIRONMENT_MANAGE','Create and modify environments' FROM dual UNION ALL
  SELECT 'CONNECTION_MANAGE','Create, configure and delete target connections' FROM dual UNION ALL
  SELECT 'DISCOVERY_RUN','Run discovery and schema analysis' FROM dual UNION ALL
  SELECT 'RULESET_CREATE','Create a Rule Set owned by the current user' FROM dual UNION ALL
  SELECT 'RULESET_MODIFY_OWN','Create drafts and modify owned Rule Sets' FROM dual UNION ALL
  SELECT 'RULESET_PUBLISH_OWN','Publish versions of owned Rule Sets' FROM dual UNION ALL
  SELECT 'RULESET_DELETE_OWN','Delete versions or owned Rule Sets' FROM dual UNION ALL
  SELECT 'JOB_MANAGE','Create, edit, cancel and delete Jobs' FROM dual UNION ALL
  SELECT 'JOB_EXECUTE','Execute and re-execute Jobs' FROM dual UNION ALL
  SELECT 'ALGORITHM_MANAGE','Create, publish and delete algorithms' FROM dual
) x ON(p.privilege_code=x.code)
WHEN MATCHED THEN UPDATE SET p.description=x.description
WHEN NOT MATCHED THEN INSERT(privilege_code,description) VALUES(x.code,x.description);

COMMIT;
