DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tables
     WHERE table_name = 'TRANSFORMATION_IMPORT';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'~
            CREATE TABLE transformation_import (
                transformation_import_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                data_source_id NUMBER NOT NULL,
                ruleset_version_id NUMBER NOT NULL,
                import_reference VARCHAR2(100 CHAR) NOT NULL,
                source_type VARCHAR2(30 CHAR) NOT NULL,
                source_name VARCHAR2(255 CHAR),
                source_sql CLOB,
                source_checksum VARCHAR2(128 CHAR) NOT NULL,
                status VARCHAR2(30 CHAR) DEFAULT 'UPLOADED' NOT NULL,
                statement_count NUMBER DEFAULT 0 NOT NULL,
                matched_count NUMBER DEFAULT 0 NOT NULL,
                warning_count NUMBER DEFAULT 0 NOT NULL,
                unresolved_count NUMBER DEFAULT 0 NOT NULL,
                created_by VARCHAR2(128 CHAR) NOT NULL,
                created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                analyzed_at TIMESTAMP WITH TIME ZONE,
                draft_created_at TIMESTAMP WITH TIME ZONE,
                CONSTRAINT transformation_import_pk PRIMARY KEY (transformation_import_id),
                CONSTRAINT transformation_import_ref_uk UNIQUE (import_reference),
                CONSTRAINT transformation_import_ds_fk FOREIGN KEY (data_source_id)
                    REFERENCES data_source (data_source_id),
                CONSTRAINT transformation_import_rv_fk FOREIGN KEY (ruleset_version_id)
                    REFERENCES ruleset_version (ruleset_version_id),
                CONSTRAINT transformation_import_status_ck CHECK (status IN (
                    'UPLOADED','ANALYZED','REVIEW_REQUIRED','DRAFT_CREATED',
                    'PUBLISHED','FAILED','CANCELLED')),
                CONSTRAINT transformation_import_count_ck CHECK (
                    statement_count >= 0 AND matched_count >= 0
                    AND warning_count >= 0 AND unresolved_count >= 0)
            )
        ~';
        DBMS_OUTPUT.PUT_LINE('[OK] TRANSFORMATION_IMPORT created');
    ELSE
        DBMS_OUTPUT.PUT_LINE('[SKIP] TRANSFORMATION_IMPORT already exists');
    END IF;
END;
